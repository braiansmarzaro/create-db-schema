/**
 * DBML formatting helpers and schema builder.
 */

/**
 * Converts a PostgreSQL data_type / udt_name to a compact DBML type string.
 */
export function toDbmlType(col) {
  const dt = col.data_type.toLowerCase();
  const udt = col.udt_name.toLowerCase();

  if (dt === 'character varying' || dt === 'varchar') {
    return col.character_maximum_length ? `varchar(${col.character_maximum_length})` : 'varchar';
  }
  if (dt === 'character' || dt === 'char') {
    return col.character_maximum_length ? `char(${col.character_maximum_length})` : 'char';
  }
  if (dt === 'numeric' || dt === 'decimal') {
    if (col.numeric_precision != null && col.numeric_scale != null) {
      return `decimal(${col.numeric_precision},${col.numeric_scale})`;
    }
    return 'decimal';
  }
  if (dt === 'integer')                return 'integer';
  if (dt === 'bigint')                 return 'bigint';
  if (dt === 'smallint')               return 'smallint';
  if (dt === 'boolean')                return 'boolean';
  if (dt === 'text')                   return 'text';
  if (dt === 'real')                   return 'float';
  if (dt === 'double precision')       return 'float8';
  if (dt === 'uuid')                   return 'uuid';
  if (dt === 'date')                   return 'date';
  if (dt.startsWith('timestamp'))      return dt.includes('time zone') ? 'timestamptz' : 'timestamp';
  if (dt === 'time without time zone') return 'time';
  if (dt === 'time with time zone')    return 'timetz';
  if (dt === 'jsonb')                  return 'jsonb';
  if (dt === 'json')                   return 'json';
  if (dt === 'bytea')                  return 'bytea';
  if (dt === 'inet')                   return 'inet';
  if (dt === 'cidr')                   return 'cidr';
  if (dt === 'macaddr')                return 'macaddr';
  if (dt === 'interval')               return 'interval';
  if (dt === 'ARRAY')                  return `${udt.replace(/^_/, '')}[]`;
  if (udt.startsWith('_'))             return `${udt.slice(1)}[]`;  // array fallback
  // User-defined types (enums, composites, etc.)
  if (dt === 'USER-DEFINED' || dt === 'user-defined') return udt;
  return dt;
}

/**
 * Returns the inline DBML settings string for a column, e.g. [pk, not null, default: `now()`]
 */
export function columnSettings(col, isPk, colComments) {
  const settings = [];

  if (isPk) settings.push('pk');

  // Auto-increment detection: serial/bigserial UDTs or nextval default
  if (
    col.udt_name === 'int4' && col.column_default?.startsWith('nextval(') ||
    col.udt_name === 'int8' && col.column_default?.startsWith('nextval(') ||
    col.data_type === 'integer' && col.column_default?.startsWith('nextval(') ||
    col.data_type === 'bigint'  && col.column_default?.startsWith('nextval(')
  ) {
    settings.push('increment');
  }

  if (col.is_nullable === 'NO' && !isPk) settings.push('not null');

  if (col.column_default != null && !col.column_default.startsWith('nextval(')) {
    const raw = col.column_default;
    // Strip explicit casts like ::text, ::character varying, ::integer, etc.
    const cleaned = raw.replace(/::[\w\s]+(\[\])?/g, '').replace(/^'(.*)'$/, "'$1'");
    settings.push(`default: \`${cleaned}\``);
  }

  const note = colComments?.get(col.column_name);
  if (note) settings.push(`note: '${note.replace(/'/g, "\\'")}'`);

  return settings.length ? ` [${settings.join(', ')}]` : '';
}

/**
 * Builds the full DBML document string from the collected schema data.
 *
 * @param {string[]} tables
 * @param {string[]} views
 * @param {object[]} columns
 * @param {Map}      primaryKeys
 * @param {Map}      allIndexes
 * @param {object[]} foreignKeys
 * @param {Map}      tableComments
 * @param {Map}      columnComments
 * @param {string}   dbName        - database name used in the file header
 */
export function buildDbml(
  tables,
  views,
  columns,
  primaryKeys,
  allIndexes,
  foreignKeys,
  tableComments,
  columnComments,
  dbName,
) {
  const lines = [];

  lines.push('// Generated by create-db-schema');
  lines.push(`// Database: ${dbName} (public schema)`);
  lines.push(`// Generated at: ${new Date().toISOString()}`);
  lines.push('');

  // Group columns by table
  const colsByTable = new Map();
  for (const col of columns) {
    if (!colsByTable.has(col.table_name)) colsByTable.set(col.table_name, []);
    colsByTable.get(col.table_name).push(col);
  }

  // Emit one Table block per table
  for (const tableName of tables) {
    const tableCols = colsByTable.get(tableName) ?? [];
    const pkCols = primaryKeys.get(tableName) ?? new Set();
    const colNotes = columnComments.get(tableName);
    const tableNote = tableComments.get(tableName);

    const headerNote = tableNote ? ` [note: '${tableNote.replace(/'/g, "\\'")}']` : '';
    lines.push(`Table ${tableName}${headerNote} {`);

    for (const col of tableCols) {
      const type = toDbmlType(col);
      const settings = columnSettings(col, pkCols.has(col.column_name), colNotes);
      lines.push(`  ${col.column_name} ${type}${settings}`);
    }

    // Indexes block
    const tableIndexes = allIndexes.get(tableName);
    if (tableIndexes && tableIndexes.length > 0) {
      lines.push('');
      lines.push('  indexes {');
      for (const idx of tableIndexes) {
        const indexCols = idx.columns.length === 1 ? idx.columns[0] : `(${idx.columns.join(', ')})`;
        const settings = [`name: '${idx.name}'`];
        if (idx.isUnique) settings.push('unique');
        lines.push(`    ${indexCols} [${settings.join(', ')}]`);
      }
      lines.push('  }');
    }

    lines.push('}');
    lines.push('');
  }

  // Emit view blocks (views have no indexes)
  if (views.length > 0) {
    lines.push('// Views');
    lines.push('');
    for (const viewName of views) {
      const viewCols = colsByTable.get(viewName) ?? [];
      const viewNote = tableComments.get(viewName);
      const colNotes = columnComments.get(viewName);
      const headerNote = viewNote
        ? ` [note: 'view — ${viewNote.replace(/'/g, "\\'")}']`
        : ` [note: 'view']`;
      lines.push(`Table ${viewName}${headerNote} {`);
      for (const col of viewCols) {
        const type = toDbmlType(col);
        // Views: nullable is always YES in information_schema, skip not-null
        const note = colNotes?.get(col.column_name);
        const settings = note ? ` [note: '${note.replace(/'/g, "\\'")}'` + ']' : '';
        lines.push(`  ${col.column_name} ${type}${settings}`);
      }
      lines.push('}');
      lines.push('');
    }
  }

  // Emit Ref lines
  if (foreignKeys.length > 0) {
    lines.push('// Foreign key references');
    for (const fk of foreignKeys) {
      // many-to-one: > means from_table.from_column references (many) to to_table.to_column (one)
      lines.push(`Ref: ${fk.from_table}.${fk.from_column} > ${fk.to_table}.${fk.to_column}`);
    }
    lines.push('');
  }

  return lines.join('\n');
}
